def retry_review(folder):
    """Rerun only the corrected actor-specific retry checks, retaining other evidence."""
    environment=json.loads((folder/'environment.json').read_text(encoding='utf-8'))
    database=Path(environment['database']).resolve()
    if os.environ.get('APP_ENV')=='production' or database.parent!=(BACKEND/'instance').resolve() or database.name=='gradpush.db':
        raise ValueError('Local test database required')
    os.environ['DATABASE_URL']='sqlite:///'+database.as_posix()
    from app import app
    from extensions import db
    from models import User
    from material_models import MaterialRecord
    from workflow_models import MaterialReviewCommand,ScoreEntry
    results=json.loads((folder/'students.json').read_text(encoding='utf-8'))
    fact=next(r for r in results[0]['records'] if r['category']=='competition' and r['scored'])
    checks=[]
    with app.app_context():
        row=db.session.get(MaterialRecord,fact['id'])
        payload=dict(version=row.version-1,decision='approve',comment='合成测试：已人工核对测试原件',idempotency_key=f'scale:{row.id}')
        prior=MaterialReviewCommand.query.filter_by(record_id=row.id,idempotency_key=payload['idempotency_key']).one()
        before=ScoreEntry.query.count()
        for name,uid,status in [('cross_actor_idempotency_conflict',User.query.filter_by(username=PREFIX+'teacher').one().id,409),
                                ('review_idempotent_replay',prior.created_by,200)]:
            client=app.test_client()
            with client.session_transaction() as session:session['user_id']=uid
            response=client.post(f'/api/materials/competition/records/{row.id}/review',json=payload)
            passed=response.status_code==status and (status!=200 or response.get_json().get('replayed') is True)
            checks.append(dict(name=name,passed=passed,status=response.status_code))
        checks.append(dict(name='review_retry_no_extra_scores',passed=before==ScoreEntry.query.count()))
    original=json.loads((folder/'boundary-checks.json').read_text(encoding='utf-8'))
    if not (folder/'boundary-checks-initial.json').exists():write_json(folder/'boundary-checks-initial.json',original)
    names={r['name'] for r in checks}
    combined=[r for r in original if r['name'] not in names]+checks
    summary=dict(checks=len(combined),passed=sum(r['passed'] for r in combined),failures=[r for r in combined if not r['passed']],
                 note='Retained previously executed passing checks; only corrected actor-specific idempotency checks rerun',
                 initial_evidence='boundary-checks-initial.json',retry_evidence='review-retry-checks.json')
    write_json(folder/'review-retry-checks.json',checks)
    write_json(folder/'boundary-checks.json',combined)
    write_json(folder/'boundary-summary.json',summary)
    guide=folder/'ACCEPTANCE.md'
    if guide.exists():
        content=guide.read_text(encoding='utf-8')
        if '## 后端重启' not in content:
            content+='\n## 后端重启\n\n计数与分页修复需重启正在运行的后端。停止原后端后，在PowerShell执行：\n\n```powershell\n'
            content+="$env:DATABASE_URL='sqlite:///D:/InteractionDesign/Myprogram/backend/instance/gradpush-dev.db'\n"
            content+='Set-Location D:\\InteractionDesign\\Myprogram\\backend\n..\\.venv\\Scripts\\python.exe app.py\n```\n'
        content+='\n边界账号：`scale28_journey`（密码同上），位于规模测试边界专业；最终学术原始34、封顶15、综合表现3、总分82。并行写入曾触发SQLite锁冲突，尚未作为并发验收通过。\n'
        guide.write_text(content,encoding='utf-8')
    print(json.dumps(summary,ensure_ascii=False),flush=True)
    return summary


