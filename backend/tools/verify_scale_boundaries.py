                while True:
                    response=clients['teacher'].get(f'/api/materials/{category}/records?reviewed={reviewed}&limit=100&after_id={cursor}&year=2028')
                    body=response.get_json() or {}
                    if response.status_code!=200:
                        check(f'{category}_{reviewed}_list_response',False,status=response.status_code); break
                    rows=body.get('records',[])
                    actual.extend(r['id'] for r in rows); pages+=1
                    next_cursor=body.get('next_after_id')
                    if next_cursor is None: break
                    if next_cursor<=cursor or pages>1000:
                        check('cursor_advances',False,category=category); break
                    cursor=next_cursor
