        check('all_originals_exist_and_hash_match',len(attachments)==sum(len(r['records']) for r in results) and not missing,count=len(attachments),missing=missing[:10])
        # Compare the generated ranking and audited export to the oracle.
        ranking=json.loads((folder/'ranking.json').read_text(encoding='utf-8'))
        exported=json.loads((folder/'ranking-export.json').read_text(encoding='utf-8'))
        expected={r['student_id']:r for r in results if r['major_id']==environment['majors'][0]['id']}
        entries=ranking.get('entries',[])
        check('ranking_population',len(entries)==len(expected) and {r['student_id'] for r in entries}==set(expected),count=len(entries))
        bad=[r['student_id'] for r in entries if Decimal(str(r['comprehensive_score']))!=Decimal(expected[r['student_id']]['expected']['score'])]
        check('ranking_all_scores',not bad,mismatches=bad[:20])
        check('audited_export_matches_ranking',exported.get('entries')==entries)
        check('export_audit_written',RankingExportAudit.query.filter_by(batch_id=ranking['batch_id']).count()>0)
        response=clients['outside'].post(f'/api/workflow/rankings/{ranking["batch_id"]}/export',json={'purpose':'跨学院越权测试'})
        check('outside_export_denied',response.status_code==403,status=response.status_code)
        response=clients['teacher'].post(f'/api/workflow/rankings/{ranking["batch_id"]}/export',json={'purpose':''})
        check('empty_export_purpose_rejected',response.status_code==400,status=response.status_code)
        # Preserve reviewable aggregate and scenario coverage.
        write_json(folder/'boundary-checks.json',checks)
        summary=dict(checks=len(checks),passed=sum(r['passed'] for r in checks),failures=[r for r in checks if not r['passed']],
                     note='Real Flask routes and SQLite; no browser, TCP concurrency or OCR-success claim')
