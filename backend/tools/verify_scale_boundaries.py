        # review list and independently query its authorized population.
        for category in ['competition','research_paper','volunteer','arts_sports','innovation_training','student_work']:
            for reviewed,statuses in [('0',['submitted','under_review']),('1',['verified','rejected','needs_correction','scored','verified_not_eligible'])]:
                expected={r.id for r in MaterialRecord.query.filter_by(category=category,faculty_id=environment['faculty_id'],year=2028).filter(MaterialRecord.status.in_(statuses)).all()}
