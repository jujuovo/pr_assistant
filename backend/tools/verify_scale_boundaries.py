    def check(name,passed,**details):
        checks.append(dict(name=name,passed=bool(passed),**details))
        if not passed: print('FAILED '+name+' '+str(details)[:800],flush=True)
        elif name.endswith('_all_pages') or name.endswith('_complete'):
            print('PASSED '+name+' '+str(details),flush=True)
