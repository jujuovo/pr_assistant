        check('invalid_requests_atomic',before==(MaterialRecord.query.count(),MaterialAttachment.query.count(),ScoreEntry.query.count()))
        # Read-only routes must leave score facts, snapshots and event counts
        # unchanged, even under repeated report / student explanation access.
        readonly_before=(ScoreEntry.query.count(),StudentScoreSnapshot.query.count(),MaterialEvent.query.count())
        for _ in range(3):
            clients['teacher'].get(f'/api/workflow/students/{results[0]["student_id"]}/score/current')
        check('read_endpoints_do_not_recalculate',readonly_before==(ScoreEntry.query.count(),StudentScoreSnapshot.query.count(),MaterialEvent.query.count()))
