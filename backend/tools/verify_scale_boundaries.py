        bad=[]
        for r in results:
            student=students[r['student_id']]
            for attr,key in [('comprehensive_score','score'),('academic_specialty_total','academic_total'),('comprehensive_performance_total','comprehensive_total')]:
                if Decimal(str(getattr(student,attr)))!=Decimal(r['expected'][key]): bad.append([r['student_id'],attr])
        check('all_compatibility_student_totals',not bad,mismatches=bad[:20])
